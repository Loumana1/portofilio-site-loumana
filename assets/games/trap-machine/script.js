    function preloadAudio() {
        // Simple preload of current kit
        Object.keys(machines).forEach(machineKey => {
            const m = machines[machineKey];
            Object.values(m.samples).flat().forEach(path => {
                new Audio(path);
            });
        });
    }

    function loadPattern(patternId) {
        if (state.isPlaying) stopPlayback();

        const patternData = patternTemplates[patternId];
        if (!patternData) return;

        // Update Pattern Name in Select if not already
        const sel = document.getElementById('pattern-select');
        if (sel.value !== patternId) sel.value = patternId;

        state.tracks = [];
        const container = document.getElementById('drumTracks');
        if (container) container.innerHTML = '';

        patternData.tracks.forEach(t => {
            addTrack(t.type, t.pattern);
        });
    }

    function addTrack(type, patternArray = null) {
        const trackId = `track-${Date.now()}-${Math.floor(Math.random() * 1000)}`;
        const pattern = patternArray ? [...patternArray] : new Array(32).fill(0);

        // Default Volume adjustments
        let defaultVol = 0.8;
        if (type === '808') defaultVol = 0.6;
        if (type === 'hihat') defaultVol = 0.7;

        const track = {
            id: trackId,
            type: type,
            pattern: pattern,
            audioPath: getAudioPath(type),
            volume: defaultVol,
            muted: false,
            solo: false
        };

        state.tracks.push(track);
        renderTrack(track);
    }

