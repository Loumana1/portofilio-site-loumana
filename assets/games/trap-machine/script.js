    // Helper to get a random sample from a list
    function getRandomSample(list) {
        if (!list || list.length === 0) return null;
        return list[Math.floor(Math.random() * list.length)];
    }

    // Function to randomize the current kit based on the active machine
    // This is called when switching machines or when user requests "Shuffle Kit"
    function randomizeCurrentKit() {
        const machine = machines[state.activeMachine];
        if (!machine) return;

        // For each type (kick, snare...), pick one random sample from the machine's list
        const newKit = {};
        const types = ['kick', 'snare', 'hihat', 'clap', '808', 'perc', 'rim'];

        types.forEach(type => {
            let samples = machine.samples[type];
            // Fallbacks if empty
            if (!samples || samples.length === 0) {
                if (type === 'clap') samples = machine.samples['snare']; // Use snare for clap
                else if (type === 'rim') samples = machine.samples['perc']; // Use perc for rim
                else if (type === '808') samples = machine.samples['kick']; // Use kick for 808
                else if (type === 'perc') samples = machine.samples['hihat']; // Use hat for perc
            }

            if (samples && samples.length > 0) {
                // If it's BNYX (default), just take the first one (since it has 1 of each in this config)
                // If it's others, pick random
                newKit[type] = getRandomSample(samples);
            }
        });

        state.currentKit = newKit;

        // Update existing tracks with new audio paths?
        // Yes, if we switch machines, we want existing pattern to sound different immediately
        state.tracks.forEach(track => {
            if (newKit[track.type]) {
                track.audioPath = newKit[track.type];
            }
        });
    }

