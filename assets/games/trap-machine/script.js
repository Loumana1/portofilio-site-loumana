    function shufflePattern() {
        // Determine genre based on current pattern name or random
        const currentPatternName = document.getElementById('pattern-select').value;
        const isDrill = currentPatternName.includes('drill');

        state.tracks.forEach(track => {
            if (isDrill) {
                track.pattern = generateDrillPattern(track.type);
            } else {
                track.pattern = generateTrapPattern(track.type);
            }
        });

        refreshSequencerUI();
    }

    function refreshSequencerUI() {
        const container = document.getElementById('drumTracks');
        container.innerHTML = '';
        state.tracks.forEach(track => renderTrack(track));
    }

    function generateTrapPattern(type) {
        const pattern = new Array(32).fill(0);

        if (type === 'kick') {
            // Trap Kick: Focused on 1, and sparse off-beats. Avoid 8/24 (snare spots)
            // Always hit 1
            pattern[0] = 1;
            for (let i = 1; i < 32; i++) {
                // Low density, avoid snare beats 8, 24
                if (i !== 8 && i !== 24 && Math.random() > 0.85) pattern[i] = 1;
            }
        }
        else if (type === 'snare' || type === 'clap') {
            // Trap Snare: Strictly on 3rd beat (step 8 [index 8? 1-based is 9? No 0-based index 8 is step 9. Wait]
            // Standard 16-step bar: Beats are 0, 4, 8, 12.
            // Half time snare on 3rd beat = step 8 (1-based step 9).
            // Let's verify indexing. Index 0 = Step 1. Index 8 = Step 9 (Beat 3). Index 24 = Step 25 (Beat 3 of bar 2).
            pattern[8] = 1;
            pattern[24] = 1;

            // Add ghost notes/fills?
            if (Math.random() > 0.7) pattern[31] = 1; // End of bar fill
            if (Math.random() > 0.8) pattern[15] = 1; // Mid bar fill
        }
        else if (type === 'hihat') {
            // Trap Hats: High density + rolls
            for (let i = 0; i < 32; i++) {
                if (Math.random() > 0.2) pattern[i] = 1; // 80% chance of 16th note

                // Simulate roll by leaving gaps? No, 1 is hit.
                // We can't do real rolls in this boolean array, but we can make it dense.
            }
            // Add gaps
            if (Math.random() > 0.5) {
                pattern[2] = 0; pattern[6] = 0; // random gaps
            }
        }
        else if (type === '808') {
            // 808 often follows kick but simpler
            pattern[0] = 1;
            for (let i = 1; i < 32; i++) {
                if (Math.random() > 0.9 && i !== 8 && i !== 24) pattern[i] = 1;
            }
        }
        else {
            // Percs/Rim - random sparse
            for (let i = 0; i < 32; i++) {
                if (Math.random() > 0.95) pattern[i] = 1;
            }
        }
        return pattern;
    }

    function generateDrillPattern(type) {
        const pattern = new Array(32).fill(0);

        if (type === 'kick') {
            // Drill Kick: Often syncopated, doubles
            pattern[0] = 1;
            // Common drill spots: Step 0, Step 10, Step 24?
            if (Math.random() > 0.5) pattern[10] = 1;
            if (Math.random() > 0.5) pattern[20] = 1;
        }
        else if (type === 'snare' || type === 'clap') {
            // Drill Snare: Beat 3 (Index 8) and often 8 (Index 24)
            // PLUS Counter snares: Index 13, 29 etc.
            if (Math.random() > 0.3) pattern[8] = 1; // Main backbeat
            pattern[24] = 1; // Main backbeat bar 2

            // Counter snares
            if (Math.random() > 0.5) pattern[13] = 1;
            if (Math.random() > 0.5) pattern[29] = 1;
        }
        else if (type === 'hihat') {
            // Drill Hats: 3+3+2 Pattern enforced
            // 3+3+2 = X--X--X- pattern repeated
            const drillGrid = [1, 0, 0, 1, 0, 0, 1, 0]; // 8 steps
            for (let i = 0; i < 32; i++) {
                if (drillGrid[i % 8]) pattern[i] = 1;
            }
        }
        else if (type === '808') {
            // Drill 808: Slides/Long notes (simulated by spacing)
            pattern[0] = 1;
            if (Math.random() > 0.5) pattern[10] = 1;
        }
        else {
            // Percs random
            for (let i = 0; i < 32; i++) {
                if (Math.random() > 0.9) pattern[i] = 1;
            }
        }
        return pattern;
    }

