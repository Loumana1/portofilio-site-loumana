    // ====================================
    // AUDIO ENGINE
    // ====================================
    let playInterval = null;
    let currentStepIndex = 0;

    function togglePlayback() {
        if (state.isPlaying) {
            stopPlayback();
        } else {
            startPlayback();
        }
    }

    function startPlayback() {
        if (state.isPlaying) return;
        state.isPlaying = true;
        updatePlayIcons(true);

        // Calculate interval
        // BPM = beats per minute
        // Step = 1/16th note = 1/4 of a beat
        // ms per beat = 60000 / BPM
        // ms per step = (60000 / BPM) / 4
        const stepTime = (60000 / state.bpm) / 4;

        playStep(); // Play first immediately
        playInterval = setInterval(playStep, stepTime);
    }

    function stopPlayback() {
        state.isPlaying = false;
        clearInterval(playInterval);
        playInterval = null;
        currentStepIndex = 0; // Reset to start? Or pause? Let's reset for now

        // Reset visual steps
        document.querySelectorAll('.step-pad.playing').forEach(el => el.classList.remove('playing'));
        updatePlayIcons(false);
    }

    function playStep() {
        const anySolo = state.tracks.some(t => t.solo);

        state.tracks.forEach(track => {
            // Determine if track should play
            const shouldPlay = anySolo ? track.solo : !track.muted;

            if (shouldPlay && track.pattern[currentStepIndex]) {
                playSound(track.audioPath, track.volume);
            }
        });

        // Visual Feedback
        // Highlight current column
        const pads = document.querySelectorAll(`.step-pad[data-step="${currentStepIndex}"]`);
        pads.forEach(p => {
            p.classList.add('playing');
            setTimeout(() => p.classList.remove('playing'), 100);
        });

        // Advance step - MODULO 32 for 2 bars
        currentStepIndex = (currentStepIndex + 1) % 32;
    }

    function playSound(path, volume) {
        const audio = new Audio(path);
        audio.volume = volume;
        // Reset time if user rapidly clicks? Audio objects are one-shot here basically.
        audio.play().catch(e => {
            // console.warn('Audio play failed (user interaction needed?):', e);
        });
    }

    function updatePlayIcons(isPlaying) {
        const btn = document.getElementById('sequencerPlayPause');
        const playIcon = btn.querySelector('.play-icon');
        const pauseIcon = btn.querySelector('.pause-icon');

        if (isPlaying) {
            btn.classList.add('playing');
            playIcon.style.display = 'none';
            pauseIcon.style.display = 'block';
        } else {
            btn.classList.remove('playing');
            playIcon.style.display = 'block';
            pauseIcon.style.display = 'none';
        }
    }

    // Start
    init();
